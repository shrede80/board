import { defineConfig } from 'vite';
import react from '@vitejs/plugin-react';
import { cloudflare } from '@cloudflare/vite-plugin';
import { execSync } from 'node:child_process';
import { readdirSync, statSync } from 'node:fs';
import { join, relative } from 'node:path';
import type { Plugin } from 'vite';

// E2E runs use their own throwaway local D1/R2 (.wrangler/e2e), wiped before each run.
const e2e = !!process.env.E2E;

/** Build version shown in «المزيد» and compared by open tabs (UPDATE-1 أ10): date + commit. */
function appVersion() {
  let sha = '';
  try {
    sha = execSync('git rev-parse --short HEAD', { stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim();
  } catch {
    /* not a git checkout */
  }
  const d = new Date().toISOString().replace(/[-:T]/g, '').slice(0, 12);
  return sha ? `${d}-${sha}` : d;
}

const VERSION = process.env.APP_VERSION || appVersion();

function publicFiles(dir: string): string[] {
  return readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    return statSync(p).isDirectory() ? publicFiles(p) : [p];
  });
}

/**
 * sw.js (UPDATE-1 ج8): caches the app shell only — the built HTML/JS/CSS, fonts, icons and
 * images of this version. Never /api/* and never any data. A new version waits until the user
 * presses «تحديث» on the new-version banner (web/src/app/sw.ts).
 */
function serviceWorker(): Plugin {
  return {
    name: 'lawhat-sw',
    apply: 'build',
    generateBundle(_, bundle) {
      if (this.environment.name !== 'client') return;
      const served = (f: string) => !f.endsWith('.map') && !f.split('/').pop()!.startsWith('.');
      const built = Object.keys(bundle).filter((f) => served(f) && f !== 'index.html');
      const pub = publicFiles('web/public').map((f) => relative('web/public', f).split('\\').join('/')).filter((f) => served(f) && f !== '_headers');
      const shell = ['/', ...[...built, ...pub].map((f) => `/${f}`)];
      const code = `// generated by vite.config.ts — app shell only, no /api, no data
const CACHE = 'shell-${VERSION}';
const SHELL = ${JSON.stringify(shell)};
self.addEventListener('install', (e) => e.waitUntil(caches.open(CACHE).then((c) => c.addAll(SHELL))));
self.addEventListener('activate', (e) => e.waitUntil(
  caches.keys().then((ks) => Promise.all(ks.filter((k) => k.startsWith('shell-') && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()),
));
self.addEventListener('message', (e) => { if (e.data === 'skipWaiting') self.skipWaiting(); });
self.addEventListener('fetch', (e) => {
  const r = e.request;
  if (r.method !== 'GET') return;
  const u = new URL(r.url);
  if (u.origin !== location.origin || u.pathname === '/api' || u.pathname.startsWith('/api/') || u.pathname === '/sw.js') return;
  if (r.mode === 'navigate') {
    e.respondWith(fetch(r).catch(() => caches.open(CACHE).then((c) => c.match('/'))));
    return;
  }
  e.respondWith(caches.open(CACHE).then((c) => c.match(r, { ignoreSearch: true })).then((hit) => hit || fetch(r)));
});
`;
      this.emitFile({ type: 'asset', fileName: 'sw.js', source: code });
    },
  };
}

export default defineConfig({
  plugins: [react(), cloudflare({ persistState: e2e ? { path: '.wrangler/e2e' } : true }), serviceWorker()],
  publicDir: 'web/public',
  define: { __APP_VERSION__: JSON.stringify(VERSION) },
  server: e2e ? { hmr: false } : undefined,
});
